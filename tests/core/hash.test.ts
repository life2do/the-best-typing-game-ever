import { describe, expect, it } from 'vitest';
import { canonicalize, CanonicalError } from '@/core/canonical';
import { hashValue, base64url } from '@/core/hash';

const fixtures = import.meta.glob('../fixtures/hash/*.json', { eager: true, import: 'default' }) as Record<
  string,
  { input: unknown; canonical: string; hash: string }
>;

describe('canonical JSON + hash fixtures (generated by an independent Python implementation)', () => {
  for (const [file, fx] of Object.entries(fixtures)) {
    it(file.split('/').pop()!, () => {
      expect(canonicalize(fx.input)).toBe(fx.canonical);
      expect(hashValue(fx.input)).toBe(fx.hash);
    });
  }
  it('has fixtures', () => expect(Object.keys(fixtures).length).toBeGreaterThanOrEqual(6));
});

describe('canonicalize restrictions', () => {
  const bad: [string, unknown, object?][] = [
    ['NaN', { a: NaN }],
    ['Infinity', [Infinity]],
    ['-0', { a: -0 }],
    ['undefined', { a: undefined }],
    ['function', { a: () => 1 }],
    ['bigint', { a: 1n }],
    ['sparse', [1, , 3]], // eslint-disable-line no-sparse-arrays
    ['Map', new Map()],
    ['non-NFC string', 'é'],
    ['float in integer-only', { v: 0.5 }, { integersOnly: true }],
    ['unsafe integer', { v: 2 ** 53 }, { integersOnly: true }],
  ];
  for (const [name, v, opts] of bad) it(`rejects ${name}`, () => expect(() => canonicalize(v, opts)).toThrow(CanonicalError));
});

describe('base64url', () => {
  it('encodes without padding', () => {
    expect(base64url(new Uint8Array([]))).toBe('');
    expect(base64url(new Uint8Array([0xfb]))).toBe('-w');
    expect(base64url(new Uint8Array([0xfb, 0xff]))).toBe('-_8');
    expect(base64url(new Uint8Array([0xfb, 0xff, 0xbf]))).toBe('-_-_');
  });
});
